import { test, expect } from "@playwright/test";
test.skip(process.env.DATAQORE_ISOLATED_TEST !== "1", "Requires the disposable full-stack fixture.");

test("business rules are authenticated, versioned and shown separately in profile and comparison results", async ({ page, request }) => {
  const base = process.env.DATAQORE_CONTROLLER_URL! + "/api/v1";
  const login = await request.post(base + "/auth/login", { headers: { Origin: process.env.DATAQORE_WEB_URL! }, data: { email: "admin@dataqore.test", password: "DataQore-test-password-2026" } });
  expect(login.ok()).toBeTruthy(); const headers = { Authorization: "Bearer " + (await login.json()).access_token };
  const post = async (path: string, data: unknown) => { const r = await request.post(base + path, { headers, data }); expect(r.ok(), await r.text()).toBeTruthy(); return r.json(); };
  const connection = await post("/connections", { name: "Business rules browser", connector: "sqlite", credentials: { database: "left.sqlite" } });
  const dataset = await post("/datasets", { connection_id: connection.id, table_name: "records" });
  expect((await request.get(base + `/datasets/${dataset.id}/quality-rules`)).status()).toBe(401);
  await page.goto("/");
  await page.getByLabel("Email", { exact: true }).fill("admin@dataqore.test");
  await page.getByLabel("Password", { exact: true }).fill("DataQore-test-password-2026");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Overview", exact: true })).toBeVisible();
  await page.goto(`/datasets/${dataset.id}`);
  await page.getByRole("button", { name: "Add rule", exact: true }).click();
  await page.getByLabel("Rule name 1", { exact: true }).fill("Minimum amount");
  await page.getByLabel("Rule column 1", { exact: true }).selectOption("amount");
  await page.getByLabel("Rule type 1", { exact: true }).selectOption("range");
  await page.getByLabel("Minimum 1", { exact: true }).fill("15.00000000000000000001");
  await page.getByRole("button", { name: "Save quality rules", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Rules saved");
  const saved = await (await request.get(base + `/datasets/${dataset.id}/quality-rules`, { headers })).json();
  expect(saved.rules[0].version).toBe(1);
  expect(saved.rules[0].definition.minimum).toBe("15.00000000000000000001");
  const profile = await post(`/datasets/${dataset.id}/profile-runs`, { sample_size: 2 });
  await expect.poll(async () => (await (await request.get(base + `/runs/${profile.id}`, { headers })).json()).status, { timeout: 20000 }).toBe("succeeded");
  await page.goto(`/runs/${profile.id}`);
  const card = page.locator("section.card").filter({ has: page.getByRole("heading", { name: "Business quality", exact: true }) });
  await expect(card.getByText("Minimum amount · v1", { exact: true })).toBeVisible();
  await expect(card).toContainText("1 passed / 2 evaluated");
  await page.screenshot({ path: "test-results/business-rules-result-desktop.png", fullPage: true });
  await page.goto(`/datasets/${dataset.id}`);
  await expect(page.getByLabel("Rule active 1")).toBeChecked();
  await page.getByLabel("Rule active 1").focus();
  await page.keyboard.press("Space");
  await page.getByRole("button", { name: "Save quality rules", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Rules saved");
  await page.reload(); await expect(page.getByLabel("Rule active 1")).not.toBeChecked();
  await page.getByRole("button", { name: "Theme", exact: true }).click();
  await page.getByRole("radio", { name: "Dark", exact: true }).check();
  await page.keyboard.press("Escape");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "test-results/business-rules-editor-mobile.png", fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.goto(`/runs/${profile.id}`); await expect(card).toContainText("Minimum amount · v1");
  const latest = await (await request.get(base + `/datasets/${dataset.id}/quality-rules`, { headers })).json();
  expect(latest.rules[0].version).toBe(2);
  await post(`/datasets/${dataset.id}/quality-rules`, { expected_revision: latest.revision, rules: [{ id: latest.rules[0].id, name: "Minimum amount", column: "amount", is_active: true, definition: { kind: "range", minimum: "15" } }] });
  const other = await post("/datasets", { connection_id: (await post("/connections", { name: "Business rules target", connector: "sqlite", credentials: { database: "right.sqlite" } })).id, table_name: "records" });
  const comparison = await post("/comparisons", { name: "Business rule comparison", left_dataset_id: dataset.id, right_dataset_id: other.id });
  const run = await post(`/comparisons/${comparison.id}/runs`, {});
  await expect.poll(async () => (await (await request.get(base + `/runs/${run.id}`, { headers })).json()).status, { timeout: 20000 }).toBe("succeeded");
  await page.goto(`/runs/${run.id}`); await expect(card).toContainText("Minimum amount · v3");
  await expect(card).toContainText("1 passed / 2 evaluated");
  await page.goto(`/comparisons/${comparison.id}`);
  await expect(card).toContainText("Minimum amount · v3");

});
