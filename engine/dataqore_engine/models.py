"""Modelos SQLAlchemy Core do schema inicial do motor; sem reflexão em execução."""
from sqlalchemy import (MetaData, Table, Column, PrimaryKeyConstraint, ForeignKeyConstraint,
    UniqueConstraint, CheckConstraint, Index, Text, text)
from sqlalchemy.dialects.postgresql import UUID, JSONB, TEXT, BOOLEAN, TIMESTAMP, INTEGER, BIGINT, NUMERIC

metadata = MetaData(schema="engine")

comparison_definitions = Table('comparison_definitions', metadata,
    Column('id', UUID(), nullable=False, server_default=text('gen_random_uuid()')),
    Column('name', TEXT(), nullable=False),
    Column('left_dataset_id', UUID(), nullable=False),
    Column('right_dataset_id', UUID(), nullable=False),
    Column('comparison_options', JSONB(astext_type=Text()), nullable=False, server_default=text("'{}'::jsonb")),
    Column('sampling_options', JSONB(astext_type=Text()), nullable=False, server_default=text('\'{"method": "rows", "rows": 1000, "max_cells": 100000, "max_sample_bytes": 16777216}\'::jsonb')),
    Column('absolute_tolerance', NUMERIC(), nullable=False, server_default=text('0')),
    Column('relative_tolerance', NUMERIC(), nullable=False, server_default=text('0')),
    Column('is_active', BOOLEAN(), nullable=False, server_default=text('true')),
    Column('created_at', TIMESTAMP(timezone=True), nullable=False, server_default=text('now()')),
    Column('updated_at', TIMESTAMP(timezone=True), nullable=False, server_default=text('now()')),
    PrimaryKeyConstraint('id', name='comparison_definitions_pkey'),
    ForeignKeyConstraint(['left_dataset_id'], ['engine.datasets.id'], name='comparison_definitions_left_dataset_id_fkey', ondelete='RESTRICT'),
    ForeignKeyConstraint(['right_dataset_id'], ['engine.datasets.id'], name='comparison_definitions_right_dataset_id_fkey', ondelete='RESTRICT'),
    UniqueConstraint('name', name='comparison_definitions_name_key'),
    CheckConstraint("absolute_tolerance >= 0::numeric AND absolute_tolerance < 'Infinity'::numeric", name='comparison_definitions_absolute_tolerance_check'),
    CheckConstraint('left_dataset_id <> right_dataset_id', name='comparison_definitions_check'),
    CheckConstraint("btrim(name) <> ''::text", name='comparison_definitions_name_check'),
    CheckConstraint("relative_tolerance >= 0::numeric AND relative_tolerance < 'Infinity'::numeric", name='comparison_definitions_relative_tolerance_check'),
    CheckConstraint("jsonb_typeof(sampling_options) = 'object'::text", name='comparison_definitions_sampling_options_check'),
    CheckConstraint("jsonb_typeof(comparison_options) = 'object'::text", name='comparison_definitions_options_check'),
    Index('comparisons_left_dataset_idx', text('left_dataset_id')),
    Index('comparisons_right_dataset_idx', text('right_dataset_id')),
)

connections = Table('connections', metadata,
    Column('id', UUID(), nullable=False, server_default=text('gen_random_uuid()')),
    Column('name', TEXT(), nullable=False),
    Column('connector', TEXT(), nullable=False),
    Column('credentials_ciphertext', TEXT(), nullable=False, comment='Payload de conexão cifrado pela aplicação com Fernet. Chave fora do database.'),
    Column('encryption_key_version', TEXT(), nullable=False, server_default=text("'v1'::text")),
    Column('is_active', BOOLEAN(), nullable=False, server_default=text('true')),
    Column('created_at', TIMESTAMP(timezone=True), nullable=False, server_default=text('now()')),
    Column('updated_at', TIMESTAMP(timezone=True), nullable=False, server_default=text('now()')),
    PrimaryKeyConstraint('id', name='connections_pkey'),
    UniqueConstraint('name', name='connections_name_key'),
    CheckConstraint("connector = ANY (ARRAY['postgresql'::text, 'mysql'::text, 'mssql'::text, 'oracle'::text, 'sqlite'::text, 'databricks'::text])", name='connections_connector_check'),
    CheckConstraint("credentials_ciphertext <> ''::text", name='connections_credentials_ciphertext_check'),
    CheckConstraint("encryption_key_version <> ''::text", name='connections_encryption_key_version_check'),
    CheckConstraint("btrim(name) <> ''::text", name='connections_name_check'),
)

datasets = Table('datasets', metadata,
    Column('id', UUID(), nullable=False, server_default=text('gen_random_uuid()')),
    Column('connection_id', UUID(), nullable=False),
    Column('catalog_name', TEXT(), nullable=False, server_default=text("''::text")),
    Column('schema_name', TEXT(), nullable=False, server_default=text("''::text")),
    Column('table_name', TEXT(), nullable=False),
    Column('metadata', JSONB(astext_type=Text()), nullable=False, server_default=text("'{}'::jsonb")),
    Column('discovered_at', TIMESTAMP(timezone=True), nullable=False, server_default=text('now()')),
    PrimaryKeyConstraint('id', name='datasets_pkey'),
    ForeignKeyConstraint(['connection_id'], ['engine.connections.id'], name='datasets_connection_id_fkey', ondelete='RESTRICT'),
    UniqueConstraint('connection_id', 'catalog_name', 'schema_name', 'table_name', name='datasets_source_identity_key'),
    CheckConstraint("jsonb_typeof(metadata) = 'object'::text", name='datasets_metadata_check'),
    CheckConstraint("table_name <> ''::text", name='datasets_table_name_check'),
)

run_results = Table('run_results', metadata,
    Column('run_id', UUID(), nullable=False),
    Column('format_version', INTEGER(), nullable=False),
    Column('conclusion', TEXT(), nullable=False),
    Column('result', JSONB(astext_type=Text()), nullable=False, comment='Resultado agregado versionado; sem linhas, chaves amostradas ou credenciais. Preservar Decimal na serialização.'),
    Column('created_at', TIMESTAMP(timezone=True), nullable=False, server_default=text('now()')),
    PrimaryKeyConstraint('run_id', name='run_results_pkey'),
    ForeignKeyConstraint(['run_id'], ['engine.runs.id'], name='run_results_run_id_fkey', ondelete='RESTRICT'),
    CheckConstraint("conclusion = ANY (ARRAY['compatible_in_sample'::text, 'difference_observed'::text, 'inconclusive'::text])", name='run_results_conclusion_check'),
    CheckConstraint('format_version > 0', name='run_results_format_version_check'),
    CheckConstraint("jsonb_typeof(result) = 'object'::text", name='run_results_result_check'),
)

run_record_evidence = Table('run_record_evidence', metadata,
    Column('run_id', UUID(), nullable=False),
    Column('ordinal', INTEGER(), nullable=False),
    Column('state', TEXT(), nullable=False),
    Column('affected_columns', JSONB(), nullable=False),
    Column('key_digest', TEXT(), nullable=False),
    Column('payload_ciphertext', TEXT(), nullable=False),
    Column('expires_at', TIMESTAMP(timezone=True), nullable=False),
    PrimaryKeyConstraint('run_id','ordinal'),
    ForeignKeyConstraint(['run_id'], ['engine.runs.id'], ondelete='RESTRICT'),
)

runs = Table('runs', metadata,
    Column('id', UUID(), nullable=False, server_default=text('gen_random_uuid()')),
    Column('kind', TEXT(), nullable=False),
    Column('comparison_id', UUID(), nullable=True),
    Column('status', TEXT(), nullable=False, server_default=text("'queued'::text")),
    Column('parameters', JSONB(astext_type=Text()), nullable=False),
    Column('idempotency_key', TEXT(), nullable=True),
    Column('requested_at', TIMESTAMP(timezone=True), nullable=False, server_default=text('now()')),
    Column('started_at', TIMESTAMP(timezone=True), nullable=True),
    Column('finished_at', TIMESTAMP(timezone=True), nullable=True),
    Column('heartbeat_at', TIMESTAMP(timezone=True), nullable=True),
    Column('error_code', TEXT(), nullable=True),
    Column('error_message', TEXT(), nullable=True),
    PrimaryKeyConstraint('id', name='runs_pkey'),
    ForeignKeyConstraint(['comparison_id'], ['engine.comparison_definitions.id'], name='runs_comparison_id_fkey', ondelete='RESTRICT'),
    UniqueConstraint('idempotency_key', name='runs_idempotency_key_key'),
    CheckConstraint("kind = 'comparison'::text AND comparison_id IS NOT NULL", name='runs_check'),
    CheckConstraint("status = 'queued'::text AND started_at IS NULL AND finished_at IS NULL OR status = 'running'::text AND started_at IS NOT NULL AND finished_at IS NULL OR status = 'succeeded'::text AND started_at IS NOT NULL AND finished_at IS NOT NULL OR status = 'failed'::text AND finished_at IS NOT NULL", name='runs_check1'),
    CheckConstraint('started_at IS NULL OR started_at >= requested_at', name='runs_check2'),
    CheckConstraint('finished_at IS NULL OR finished_at >= requested_at', name='runs_check3'),
    CheckConstraint('finished_at IS NULL OR started_at IS NULL OR finished_at >= started_at', name='runs_check4'),
    CheckConstraint("idempotency_key IS NULL OR idempotency_key <> ''::text", name='runs_idempotency_key_check'),
    CheckConstraint("kind = ANY (ARRAY['comparison'::text])", name='runs_kind_check'),
    CheckConstraint("jsonb_typeof(parameters) = 'object'::text", name='runs_parameters_check'),
    CheckConstraint("status = ANY (ARRAY['queued'::text, 'running'::text, 'succeeded'::text, 'failed'::text])", name='runs_status_check'),
    Index('runs_active_idx', text('heartbeat_at'), postgresql_where=text("(status = 'running'::text)")),
    Index('runs_comparison_idx', text('comparison_id'), text('requested_at DESC')),
    Index('runs_queue_idx', text('requested_at'), text('id'), postgresql_where=text("(status = 'queued'::text)")),
)
